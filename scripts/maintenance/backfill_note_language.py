"""Add a Danish `da:` leaf to the `verification_note` mappings already in
`data/v2/final/**`.

WHY A MIGRATION IS NEEDED AT ALL
--------------------------------
Every one of these notes came from a template in a seed builder, and those
templates now carry Danish. That fixes nothing for the ~9 900 notes already
on disk: absorb GAP-FILLS `verification_note` (`_enrich_final_entry`) rather
than overwriting it, so a note that exists is never re-derived from its
generator. The same property that makes a curated rewrite survive a re-flow
makes a generator change invisible to the existing data. Both halves are
needed — the generator for new coins, this script for the ones that are here.
(Same shape as §9's exclusions: tightening a parser filter never removes a
coin already in the seed.)

WHY NOT RE-EMIT THE FILE
------------------------
`dump_v2_canonical` round-trips only 5 of the 24 final yamls byte-for-byte;
the other 19 come back with different line-wrapping in long folded scalars.
Re-emitting would bury ~30 added lines under thousands of rewrap lines and
make `verify_reflow.py`'s output unreadable. So this edits the raw text and
inserts one folded line per note, leaving every other byte alone.

WHY ONLY `final/`
-----------------
`final/` is what the build renders. The seeds are regenerated by builders
that now emit `da` themselves, so backfilling them would be churn that the
next re-seed produces anyway.

SCOPE
-----
Only the fixed-text template families below, and by default only the eight
entities the Danish page consumes — Danish renders nowhere else. Notes whose
text is interpolated per coin (the Hede overview-row note quotes the index
line; the canonical-fineness notes carry a Müntzfuß name and a Δ) and the
hand-written per-coin notes are NOT translated here: each is its own piece of
prose, and a template cannot stand in for it. They keep falling back to
English, which is what every untranslated surface on that site does today.
The run prints how many notes it left behind, and that number is the point —
it is the remaining work, not a rounding error.
"""
