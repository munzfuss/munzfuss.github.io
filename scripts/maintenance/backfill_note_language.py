# The emitter shares one mapping object across every coin that carries the
# same generated note, so it writes ONE anchored definition and thousands of
# aliases (`verification_note: *id005`). Editing the definition reaches all of
# them — an alias has no block of its own and is skipped by falling through.
_NOTE_RE = re.compile(r"^(?P<indent>\s*)verification_note:(?: +&\S+)?\s*$")
_LANG_RE = re.compile(r"^(?P<indent>\s*)(?P<lang>de|en|uk|da): (?P<rest>.*)$")


def unfold(first: str, cont: list[str]) -> str:
    """Rebuild a folded YAML scalar into the string it parses to."""
    return yaml.safe_load(
        "v: " + first + "".join("\n  " + c.strip() for c in cont)
    )["v"]


def fold(indent: str, key: str, text: str) -> list[str]:
    """Emit `key: text` folded at FOLD_WIDTH, the way ruamel would.

    Quoted rather than plain when the text would otherwise be ambiguous —
    every Danish string here opens with a letter, but several contain «: »
    inside (`Hede-seed: …`), which forces it.
    """
    if ": " in text or " #" in text or text[:1] in "-?:,[]{}#&*!|>'\"%@`":
        text = "'" + text.replace("'", "''") + "'"
    cont = indent + "  "
    lines, cur = [], f"{indent}{key}: "
    for w in text.split(" "):
        if cur.strip() and len(cur) + len(w) + 1 > FOLD_WIDTH:
            lines.append(cur.rstrip() + " ")
            cur = cont
        cur += w + " "
    lines.append(cur.rstrip())
    return lines


def process(raw: str) -> tuple[str, int, int]:
    """Return (new text, notes given a `da`, notes left without one)."""
    lines = raw.split("\n")
    out: list[str] = []
    added = skipped = 0
    i = 0
    while i < len(lines):
        m = _NOTE_RE.match(lines[i])
        if not m:
            out.append(lines[i])
            i += 1
            continue
        note_indent = m.group("indent")
        out.append(lines[i])
        i += 1
        # Collect the whole mapping: language keys at note_indent + 2, each
        # possibly followed by deeper-indented continuation lines.
        block: list[str] = []
        langs: dict[str, str] = {}
        key = None
        first = ""
        cont: list[str] = []

        def close():
            if key:
                langs[key] = unfold(first, cont)

        while i < len(lines):
            line = lines[i]
            if not line.strip():
                break
            lm = _LANG_RE.match(line)
            if lm and lm.group("indent") == note_indent + "  ":
                close()
                key, first, cont = lm.group("lang"), lm.group("rest"), []
                block.append(line)
                i += 1
                continue
            if key and line.startswith(note_indent + "    "):
                cont.append(line)
                block.append(line)
                i += 1
                continue
            break
        close()
        out.extend(block)
        if not langs:
            continue
        if "da" in langs:
            continue
        da = DA_BY_EN.get(langs.get("en", ""))
        if da is None:
            da = da_from_pattern(langs.get("de", ""))
        if da is None:
            skipped += 1
            continue
        out.extend(fold(note_indent + "  ", "da", da))
        added += 1
    return "\n".join(out), added, skipped


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--apply", action="store_true",
                    help="write changes (default: dry run)")
    ap.add_argument("--all-entities", action="store_true",
                    help="every final yaml, not only the Danish-page ones")
    args = ap.parse_args()

    if args.all_entities:
        targets = sorted(FINAL.glob("*.yml"))
    else:
        targets = [FINAL / f"{e}.yml" for e in DANISH_ENTITIES]

    total_added = total_skipped = 0
    for path in targets:
        if not path.is_file():
            print(f"  ??  {path.name} — not found")
            continue
        raw = path.read_text(encoding="utf-8")
        new, added, skipped = process(raw)
        total_added += added
        total_skipped += skipped
        if added:
            print(f"  {added:5}  +da   {skipped:4} left   {path.name}")
            # Parse guard: the file must still load, and adding a key must
            # not have changed anything else about it.
            before, after = yaml.safe_load(raw), yaml.safe_load(new)
            # Strip `da` from BOTH sides: on a second run the file already
            # carries the leaves an earlier pass added, and stripping only the
            # new document would report those as a loss.
            _strip_da(before)
            _strip_da(after)
            assert before == after, f"{path.name}: the edit changed more than `da`"
            if args.apply:
                path.write_text(new, encoding="utf-8")
        elif skipped:
            print(f"      0  +da   {skipped:4} left   {path.name}")
    print(f"{'applied' if args.apply else 'would add'}: {total_added} Danish "
          f"notes; {total_skipped} left in English "
          f"(per-coin or interpolated prose — not template text)")
    if not args.apply:
        print("(dry run — pass --apply to write)")
    return 0


